package dev.bounded.compiler.backend;

import dev.bounded.compiler.api.generate.GeneratedClass;
import dev.bounded.compiler.api.write.OutputTarget;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.contains;
import static org.hamcrest.Matchers.is;
import static org.junit.jupiter.api.Assertions.assertThrows;

class ClassFileWriterTest {
    private final ClassFileWriter writer = new ClassFileWriter();
    private final GeneratedClass generatedClass = new GeneratedClass("bounded.generated.Bounded_Amount", new byte[]{1, 2, 3});

    @TempDir
    Path temporaryDirectory;

    @Test
    @DisplayName("Places the class file under its package directories")
    void writesToPackageDirectory() throws IOException {
        var result = writer.write(generatedClass, new OutputTarget(temporaryDirectory));

        assertThat(result.generatedClassFiles(), contains(temporaryDirectory.resolve("classes/bounded/generated/Bounded_Amount.class")));
    }

    @Test
    @DisplayName("Writes the generated bytecode exactly")
    void writesBytecode() throws IOException {
        var classPath = writer.write(generatedClass, new OutputTarget(temporaryDirectory)).generatedClassFiles().getFirst();

        assertThat(Files.readAllBytes(classPath), is(generatedClass.bytecode()));
    }

    @Test
    @DisplayName("Replaces an existing class file with the new bytecode")
    void replacesExistingClassFile() throws IOException {
        var classPath = writer.write(generatedClass, new OutputTarget(temporaryDirectory)).generatedClassFiles().getFirst();
        var replacement = new GeneratedClass(generatedClass.qualifiedClassName(), new byte[]{4});

        writer.write(replacement, new OutputTarget(temporaryDirectory));

        assertThat(Files.readAllBytes(classPath), is(new byte[]{4}));
    }

    @Test
    @DisplayName("Propagates filesystem failures")
    void propagatesFilesystemFailures() throws IOException {
        var outputRoot = Files.writeString(temporaryDirectory.resolve("output"), "occupied");

        assertThrows(IOException.class, () -> writer.write(generatedClass, new OutputTarget(outputRoot)));
    }
}
