package dev.bounded.compiler.backend;

import dev.bounded.compiler.api.generate.ClassName;
import dev.bounded.compiler.api.generate.GeneratedClass;
import dev.bounded.compiler.api.generate.GeneratedProgram;
import dev.bounded.compiler.api.write.OutputTarget;
import dev.bounded.compiler.api.write.WriteResult;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.contains;
import static org.hamcrest.Matchers.is;
import static org.hamcrest.Matchers.startsWith;
import static org.junit.jupiter.api.Assertions.assertThrows;

@DisplayName("Class artifact writing")
class ClassFileWriterTest {
    private final ClassFileWriter writer = new ClassFileWriter();
    private final GeneratedClass generatedClass = new GeneratedClass(new ClassName("bounded.generated.Bounded_Amount"), new byte[]{1, 2, 3});

    @TempDir
    Path temporaryDirectory;

    @Test
    @DisplayName("Reports the binary name, class path root, and package-relative file")
    void writesToPackageDirectory() throws IOException {
        var artifact = write(generatedClass).artifacts().getFirst();
        var root = temporaryDirectory.toRealPath().resolve("classes");
        assertThat(artifact.className(), is(generatedClass.className()));
        assertThat(artifact.classPathRoot(), is(root));
        assertThat(artifact.classFile(), is(root.resolve("bounded/generated/Bounded_Amount.class")));
    }

    @Test
    @DisplayName("Writes the generated bytecode exactly")
    void writesBytecode() throws IOException {
        var classPath = write(generatedClass).artifacts().getFirst().classFile();
        assertThat(Files.readAllBytes(classPath), is(generatedClass.bytecode()));
    }

    @Test
    @DisplayName("Replaces an existing class file with the new bytecode")
    void replacesExistingClassFile() throws IOException {
        var classPath = write(generatedClass).artifacts().getFirst().classFile();
        var replacement = new GeneratedClass(generatedClass.className(), new byte[]{4});
        write(replacement);
        assertThat(Files.readAllBytes(classPath), is(new byte[]{4}));
    }

    @Test
    @DisplayName("Writes every generated class, including a class in the default package")
    void writesMultipleClasses() throws IOException {
        var helper = new GeneratedClass(new ClassName("Helper"), new byte[]{4, 5});
        var artifacts = write(generatedClass, helper).artifacts();
        assertThat(artifacts.stream().map(artifact -> artifact.className().binaryName()).toList(),
                contains(generatedClass.qualifiedClassName(), "Helper"));
        assertThat(Files.readAllBytes(artifacts.get(0).classFile()), is(generatedClass.bytecode()));
        assertThat(Files.readAllBytes(artifacts.get(1).classFile()), is(helper.bytecode()));
    }

    @Test
    @DisplayName("Propagates filesystem failures")
    void propagatesFilesystemFailures() throws IOException {
        var outputRoot = Files.writeString(temporaryDirectory.resolve("output"), "occupied");
        assertThrows(IOException.class, () -> writer.write(
                new GeneratedProgram(List.of(generatedClass)), new OutputTarget(outputRoot)));
    }

    @DisplayName("Refuses to follow symbolic links in generated package directories")
    @ParameterizedTest(name = "Rejects a symbolic link at {0}")
    @ValueSource(strings = {"classes", "classes/bounded", "classes/bounded/generated"})
    void rejectsSymbolicDirectories(String relativePath) throws IOException {
        var outside = Files.createDirectory(temporaryDirectory.resolve("outside"));
        var output = Files.createDirectory(temporaryDirectory.resolve("output"));
        var link = output.resolve(relativePath);
        Files.createDirectories(link.getParent());
        Files.createSymbolicLink(link, outside);
        var failure = assertThrows(IOException.class, () -> writer.write(
                new GeneratedProgram(List.of(generatedClass)), new OutputTarget(output)));
        assertThat(failure.getMessage(), startsWith("Cannot write through symbolic link: "));
        try (var contents = Files.list(outside)) {
            assertThat(contents.count(), is(0L));
        }
    }

    @Test
    @DisplayName("Refuses to overwrite a file through a symbolic link")
    void rejectsSymbolicClassFile() throws IOException {
        var outside = Files.write(temporaryDirectory.resolve("outside.class"), new byte[]{9});
        var parent = Files.createDirectories(temporaryDirectory.resolve("classes/bounded/generated"));
        Files.createSymbolicLink(parent.resolve("Bounded_Amount.class"), outside);
        assertThrows(IOException.class, () -> write(generatedClass));
        assertThat(Files.readAllBytes(outside), is(new byte[]{9}));
    }

    @Test
    @DisplayName("A failed write leaves earlier artifacts in place and does not return success")
    void preservesCompletedWritesOnFailure() throws IOException {
        Files.createDirectories(temporaryDirectory.resolve("classes/Occupied.class"));
        var second = new GeneratedClass(new ClassName("Occupied"), new byte[]{4});
        assertThrows(IOException.class, () -> write(generatedClass, second));
        var firstFile = temporaryDirectory.resolve("classes/bounded/generated/Bounded_Amount.class");
        assertThat(Files.readAllBytes(firstFile), is(generatedClass.bytecode()));
        assertThat(Files.isDirectory(temporaryDirectory.resolve("classes/Occupied.class")), is(true));
    }

    private WriteResult write(GeneratedClass... classes) throws IOException {
        return writer.write(new GeneratedProgram(List.of(classes)), new OutputTarget(temporaryDirectory));
    }
}
